/**
 * The single place a site engine plugs in.
 *
 * nginx, Apache, and OpenLiteSpeed all follow the same sequence on every
 * apply — render a per-site config, stage it **only when its bytes changed**,
 * swap it in, config-test, reload (or restart) the matching `turbopanel-*`
 * unit, and prove over HTTP that the engine still answers. That sequence used
 * to exist three times, once per engine, with the differences buried inside
 * each copy. It lives here once, and the differences are data:
 *
 * - **`configGroup` / `stageSiteConfig`** — nginx and Apache site files are
 *   installed `root:<engineGroup>` `0640` through `sudo -n install`, so the
 *   daemon (which is not root) can neither read nor write them afterwards.
 *   OpenLiteSpeed *fragments* are deliberately daemon-owned instead: the
 *   aggregated `httpd_config.conf` is regenerated by reading every fragment
 *   back, which a privileged-only file would make impossible. Same
 *   unchanged-content discipline either way, different compare strategy.
 * - **`configTest`** — `nginx -t` runs as `tpnginx`, `httpd -t` runs as root,
 *   and `openlitespeed -t` runs as `tpols`.
 * - **`reload`** — always `systemctl reload`, falling back to
 *   `enable --now` on a host that has never started the unit.
 *
 * ## Safe rollout
 *
 * {@link rolloutSiteConfigs} is the transaction every apply goes
 * through. A rendered config is never written straight to its live path:
 *
 * 1. **Stage.** The candidate lands at `<path>.tpnew` — same directory, so the
 *    swap below is a same-filesystem rename, and *not* matching the `*.conf`
 *    glob every engine's main config includes, so the engine cannot see it yet.
 *    The bytes currently live at `<path>` are snapshotted to `<path>.tpprev`
 *    in the same step; that snapshot is the last-known-good config.
 * 2. **Swap.** Every staged candidate for one engine is renamed into place in
 *    one pass. A rename is atomic, so no reader ever sees a half-written vhost.
 * 3. **Config-test.** `nginx -t` / `httpd -t` / `openlitespeed -t` all validate
 *    a *main* config and everything it includes — never a lone fragment — so
 *    the earliest instant an engine-native test can see the candidate is right
 *    after the swap. It runs there, with `<path>.tpprev` still holding the
 *    previous bytes.
 * 4. **Reload**, then **HTTP validation** against each site's loopback listener.
 * 5. **Roll back on any failure.** A failed config-test, a failed reload, or an
 *    engine that stops answering all restore `<path>.tpprev` over `<path>`
 *    (or delete `<path>` when the site is new), then re-test and reload the
 *    restored config. A deploy therefore cannot strand a config on disk that
 *    the engine refuses — the next reload or restart still finds the last
 *    config this host is known to have served.
 *
 * php-fpm is not an engine (it serves no port and owns no vhost) but it shares
 * the stage-test-reload shape, so it is expressed as a driver too — see
 * {@link PHP_FPM_DRIVER} for why it never restarts.
 */

