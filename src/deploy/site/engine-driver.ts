export const OPENLITESPEED_DRIVER: SiteEngineDriver = {
  engine: "openlitespeed",
  label: "OpenLiteSpeed",
  unit: "turbopanel-openlitespeed",
  // Fragments stay daemon-owned so the aggregated httpd_config.conf can be
  // regenerated by reading every currently-active fragment back.
  configGroup: null,
  stageSiteConfig(_run, path, contents) {
    return stageDaemonConfigFile(path, contents);
  },
  async configTest(run, layout) {
    // `openlitespeed -t` parses httpd_config.conf plus every per-vhost
    // configFile it names and exits without binding a port. Run it as tpols,
    // the account the unit runs as: the parse resolves each vhost's suEXEC
    // user/group and its LSAPI socket path relative to the server root, so a
    // root-owned test would validate paths the service can never reach.
    const test = await run("sudo", [
      "-n",
      "-u",
      "tpols",
      "--",
      openlitespeedBinaryPath(layout),
      "-t",
      "-c",
      openlitespeedMainConfigPath(layout),
    ]);
    if (!test.success) {
      throw new Error(test.stderr || "openlitespeed -t failed");
    }
  },
  async reload(run, layout, restart) {
    // `systemctl reload` maps to `lswsctrl restart` (graceful, zero-downtime —
    // OpenLiteSpeed has no separate "reload" signal distinct from restart), and
    // a restart is exactly where an unvalidated config would surface as
    // downtime, so the config-test above always runs first.
    await this.configTest(run, layout);
    await systemctlReloadOrStart(run, this.unit, restart, this.label);
  },
};

